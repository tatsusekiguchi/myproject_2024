				<p>　名古屋大学東山キャンパスにおいて，日本犯罪心理学会第60回大会を開催することとなりました。新型コロナウイルスが，今後の私たちの生活にどのような影響を及ぼすのか，なかなか先の読めない状況ではありますが，今のところ，本大会は，できる限り従来の方法に近い形で開催する予定です。すでに，大学や関係機関の方々の協力を得て準備委員会を立ち上げ，企画を練っています。</a><br>
　大会のテーマは，「脳からみた非行・犯罪」です。昨今，今までブラックボックスとされてきたヒトの生物学的側面に関するさまざまな情報が明らかになっています。その最たるものが，脳機能の解明ではないでしょうか。従来から，私たちは，心という装置を想定し，心理学の理論や概念の枠組みをよりどころとして，非行少年や犯罪者たちを観察し，理解してきました。その価値は，時代を経てなお，色あせるものではありませんが，さらに，脳科学の知見を取り入れることによって，心理学だけでは見えてこなかった，非行少年や犯罪者というヒトをよりよく理解するための手がかりを得ることができることでしょう。</a><br>
　全体シンポジウムでは，4人のシンポジストにご登壇いただきます。シンポジストは，社会的敗北ストレス経験が個体にどのような影響をおよぼすのかを検討している動物心理学者，個体の生物学的特性が環境との交互作用でどのように変化するのかを検討する行動遺伝学者，心理臨床をベースに従来の心理学が想定していた「こころ」と脳との関係を解き明かす精神医学者，犯罪行為の発現と適応の過程を解明しようと試みる犯罪心理学者で構成されています。彼らからの話題提供をもとに，生物学的機序を非行少年・犯罪者への理解と支援に生かすためのヒントや，再非行・再犯防止，社会復帰へと結びつける方法について議論する予定です。シンポジストはみな，その分野のスペシャリストであり，豊富な知見をお持ちです。実務にも生かせる大変有意義な内容となっておりますので，どうぞご期待ください。</a><br>
　その他の大会準備委員会企画ミニシンポジウムでは，犯罪の予防的抑止や特殊詐欺などをテーマに，各領域をリードする専門家による話題提供を予定しております。概要をホームページにアップしてありますので，そちらも合わせてご覧ください。さらに，会員のみなさまからの公募シンポジウムも受けつけます。本学会のホームページをご覧いただき，募集要項をご確認ください。</a><br>
　多くの会員のみなさまと活発に議論を交わしながら，新たな研究と実践の発展につなげることができれば幸いです。感染症対策にも十分配慮しておりますので，安心してご来場ください。みなさまのご参加を，心よりお待ち申し上げております。
</p>
