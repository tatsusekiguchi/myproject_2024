			<h2>Greeting from the President of the Japanese Association of Criminal Psychology (JACP)</h2>
			<div class="cntBox">
				<p>Japanese Association of Criminal Psychology is an academic body researching delinquency and crime from psychological perspectives. You can read about the Association members' research in the "Encyclopedia of Criminal Psychology" (2016), published by Maruzen Publishing Co., Ltd., which was compiled through their efforts.</p>
				<p>The Association has approximately 1500 members, a relatively large number for a psychology research association. One characteristic of the Association is that many of its members are practitioners working in criminal justice, including the Japanese Ministry of Justice, the police, the courts. As a result, they conduct practical research on criminal psychology.</p>
				<p>The study of criminal phenomena in Japanese psychology has an extensive history. We know that Yujiro Motora (1858-1912), the founder of psychology in Japan, encouraged Seiichi Terada (1884-1922) to investigate criminal psychology after learning that Eiichi Makino (1878-1970), a legal scholar, advocated positivism for understanding criminal behavior. The history of the Association is described in the history section of this website. Moreover, all articles published since the inauguration of the Association are available on J-stage. We invite you to read these articles and discover how the Association has fostered empirical research in criminal psychology.</p>
				<p>The Association organizes research meetings and other events, an annual conference, and a journal publication. We also offer research grants to young researchers and prizes awarded every three years to encourage research. We look forward to the applications of highly motivated young researchers for these awards and accolades.</p>
				<p>We have recently enhanced the Associations' Internet-based information sharing environment, in part because of the need to prevent COVID-19.  We will use the pandemic as an opportunity to revitalize the Association by harnessing the Internet for increasing the Association's impact. Also, more universities are offering courses related to criminal psychology because the Certified Public Psychologists Act stipulates taking criminal psychology courses in the university as a prerequisite for becoming the Certified Public Psychologist. Consequently, we intend to disseminate further the Association's knowledge for training the next generation of psychologists.</p>
				<p>I was elected the Association's president at the 2021 General Meeting. I am committed to doing everything in my power to energize the Association by taking into account the views and opinions of all its members. I look forward with great pleasure to working with you in the future endeavors of the Japanese Association of Criminal Psychology.</p>
				<p class="name">（October, 2021）<br>Kyoko Fujino, President of Japanese Association of Criminal Psychology</p>
