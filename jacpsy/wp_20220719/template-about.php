				<p>　本学会は，学会誌の発行，年１回の大会に加えて，研究会等も実施しています。若手研究者のための研究助成制度があり，３年に１度研究奨励賞の授与も行っています。意欲ある若手研究者の積極的な参加を期待しています。</p>
				<p>　コロナ禍，対面での活動を控える状況に後押しされたこともあって，ネットでの情報発信・共有の環境が改善されましたので，ネットも活用しながら学会の一層の活性化を図る予定です。また，公認心理師法施行に伴い，本学会の研究領域に係る講義を行う大学が増えましたが，その知識の普及や次世代の担い手の育成の在り方に我々の学会の知見をどのように活かしていくかも課題であると認識しています。</p>				
